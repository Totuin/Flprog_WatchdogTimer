#pragma once

#include "flprogUtilites.h"

#ifdef RT_HW_CORE_RP2040
#include <hardware/regs/m0plus.h>
#include <hardware/regs/addressmap.h>
// Регистр AIRCR ядра ARM: бит SYSRESETREQ запрашивает системный сброс.
#define AIRCR_Register (*((volatile uint32_t *)(PPB_BASE + 0x0ED0C)))
#endif

/**
 * Обработчик, вызываемый непосредственно перед программным перезапуском.
 * ВАЖНО: tick() обычно вызывается из прерывания аппаратного таймера, поэтому
 * обработчик должен быть коротким и неблокирующим. Нельзя использовать delay(),
 * ожидание Serial, динамические выделения памяти и прочие небезопасные для ISR операции.
 *
 * Историческое написание имени FLProgrog сохранено ради совместимости проектов.
 */
typedef void (*FLProgrogWatchdogTimerEvent)();

/**
 * Программный сторожевой таймер для контроля выполнения основного цикла.
 *
 * Вызывать pool() из loop(), а tick() — через периодический аппаратный таймер.
 * Если pool() не вызывался в течение checkPeriod секунд, сработает обработчик
 * и будет сделана попытка перезапустить микроконтроллер.
 *
 * Таймер требует продолжающих работать прерываний: это НЕ аппаратный watchdog,
 * и зависание с отключёнными прерываниями он обнаружить не сможет.
 *
 * Настройку периода следует выполнять из обычного кода (setup()/loop()),
 * а не из обработчика прерывания. Желательно закончить настройку при запуске.
 */
class FLProgrogWatchdogTimer
{
public:
    /**
     * @param checkPeriod Время ожидания активности loop() в секундах (1..255).
     *                    Нулевое значение отклоняется: остаётся 10 секунд.
     */
    explicit FLProgrogWatchdogTimer(uint8_t checkPeriod);

    /** Подтверждение работоспособности основного цикла; вызывать из loop(). */
    void pool();

    /** Один шаг сторожевого таймера; обычно вызывается из ISR аппаратного таймера. */
    void tick();

    /** Изменить время ожидания в секундах; ноль игнорируется. */
    void setCheckPeriod(uint8_t checkPeriod);

    /** Установить необязательный обработчик, выполняемый перед перезапуском. */
    void setCallBack(FLProgrogWatchdogTimerEvent func) { _callBack = func; }

    /**
     * Установить период вызова tick() в микросекундах; ноль игнорируется.
     * Аргумент должен соответствовать фактическому периоду аппаратного таймера.
     */
    void setTickPeriod(uint32_t tickPeriod);

private:
    /** Пересчитать порог числа вызовов tick() и начать новый интервал контроля. */
    void calculateTickValue();

    /** Вызвать callback и выполнить поддерживаемый для платформы перезапуск. */
    void execureRestart();

    FLProgrogWatchdogTimerEvent _callBack = 0;

    uint8_t _checkPeriod = 10; // секунды; корректный диапазон 1..255

    // Флаг вместо счётчика: при очень быстром loop() старый uint16_t мог
    // переполниться ровно между двумя прерываниями. Байтовая запись атомарна
    // на поддерживаемых 8-битных AVR и обычных 32-битных платформах.
    volatile uint8_t _loopSeen = 0;

    // Эти поля принадлежат обработчику tick(). Периоды настраивать в setup(),
    // чтобы не было одновременной записи из loop() и чтения из прерывания.
    uint32_t _tickCounter = 0;
    uint32_t _tickValue = 1000000; // при 10 секундах и тике 10 мкс
    uint32_t _tickPeriod = 10;     // микросекунды
};
